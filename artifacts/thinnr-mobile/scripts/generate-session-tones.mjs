/**
 * Generates lib/session-tones.ts — the tiny WAV data URIs the guided
 * progress-photo session plays during its countdown (per-second tick,
 * shutter confirmation, problem alert).
 *
 * Baking the tones in as base64 constants keeps them out of the Metro
 * asset pipeline entirely: the same data URI plays through expo-audio on
 * iOS, Android, and web, and the verify suite can validate the WAV headers
 * without touching the filesystem.
 *
 * Run from artifacts/thinnr-mobile:  node scripts/generate-session-tones.mjs
 */
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const SAMPLE_RATE = 22050;

/** 16-bit mono PCM WAV from float samples (-1..1). */
function wavFromSamples(samples) {
  const dataLength = samples.length * 2;
  const buffer = Buffer.alloc(44 + dataLength);
  buffer.write('RIFF', 0, 'ascii');
  buffer.writeUInt32LE(36 + dataLength, 4);
  buffer.write('WAVE', 8, 'ascii');
  buffer.write('fmt ', 12, 'ascii');
  buffer.writeUInt32LE(16, 16); // PCM chunk size
  buffer.writeUInt16LE(1, 20); // PCM format
  buffer.writeUInt16LE(1, 22); // mono
  buffer.writeUInt32LE(SAMPLE_RATE, 24);
  buffer.writeUInt32LE(SAMPLE_RATE * 2, 28); // byte rate
  buffer.writeUInt16LE(2, 32); // block align
  buffer.writeUInt16LE(16, 34); // bits per sample
  buffer.write('data', 36, 'ascii');
  buffer.writeUInt32LE(dataLength, 40);
  for (let i = 0; i < samples.length; i += 1) {
    const clamped = Math.max(-1, Math.min(1, samples[i]));
    buffer.writeInt16LE(Math.round(clamped * 32767), 44 + i * 2);
  }
  return buffer;
}

/**
 * A tone made of one or more sine segments, with a short fade at both ends
 * of each segment so there is never a click.
 */
function tone(segments, gain = 0.5) {
  const samples = [];
  for (const { freq, ms } of segments) {
    const count = Math.round((SAMPLE_RATE * ms) / 1000);
    const fade = Math.min(Math.round(SAMPLE_RATE * 0.008), Math.floor(count / 3));
    for (let i = 0; i < count; i += 1) {
      let amp = gain;
      if (i < fade) amp *= i / fade;
      if (i >= count - fade) amp *= (count - 1 - i) / fade;
      samples.push(amp * Math.sin((2 * Math.PI * freq * i) / SAMPLE_RATE));
    }
  }
  return samples;
}

const tick = wavFromSamples(tone([{ freq: 880, ms: 70 }], 0.42));
// Rising two-note "shot taken" confirmation.
const capture = wavFromSamples(tone([{ freq: 988, ms: 110 }, { freq: 1319, ms: 190 }], 0.5));
// Low, gentle "something needs attention" tone.
const alert = wavFromSamples(tone([{ freq: 330, ms: 150 }, { freq: 262, ms: 190 }], 0.5));

const moduleSource = `/**
 * AUTO-GENERATED by scripts/generate-session-tones.mjs — do not edit by
 * hand; rerun the script to change a tone.
 *
 * Tiny 16-bit mono WAVs, baked in as data URIs so expo-audio plays the
 * exact same bytes on iOS, Android, and web with no asset pipeline in the
 * middle. Total footprint is ~40 KB of source.
 */

/** Per-second countdown tick (880 Hz, 70 ms). */
export const TICK_TONE_URI =
  'data:audio/wav;base64,${tick.toString('base64')}';

/** Shutter confirmation — rising two-note chime. */
export const CAPTURE_TONE_URI =
  'data:audio/wav;base64,${capture.toString('base64')}';

/** Gentle low alert for capture/save problems. */
export const ALERT_TONE_URI =
  'data:audio/wav;base64,${alert.toString('base64')}';
`;

const outPath = join(dirname(fileURLToPath(import.meta.url)), '..', 'lib', 'session-tones.ts');
writeFileSync(outPath, moduleSource);
console.log(`Wrote ${outPath}`);
