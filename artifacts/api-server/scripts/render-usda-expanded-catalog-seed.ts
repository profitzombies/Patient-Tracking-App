/**
 * Renders the idempotent 5,000-row USDA SR Legacy catalog expansion.
 *
 * Run from api-server:
 *   pnpm exec tsx scripts/render-usda-expanded-catalog-seed.ts 1 \
 *     > ../../supabase/migrations/20260925110000_seed_usda_catalog_expansion_1.sql
 *   pnpm exec tsx scripts/render-usda-expanded-catalog-seed.ts 2 \
 *     > ../../supabase/migrations/20260925120000_seed_usda_catalog_expansion_2.sql
 */
import { USDA_CATALOG_EXPANDED_SEED_ROWS } from '../src/catalog/usda-seed';

function json(value: unknown): string {
  const serialized = JSON.stringify(value);
  if (serialized.includes('$seed_')) throw new Error('Seed data conflicts with SQL dollar-quote tag');
  return serialized;
}

const part = Number(process.argv[2]);
const partSize = 2_500;
if (part !== 1 && part !== 2) {
  throw new Error('Pass expansion part 1 or 2');
}
const partRows = USDA_CATALOG_EXPANDED_SEED_ROWS.slice((part - 1) * partSize, part * partSize);
if (partRows.length !== partSize) {
  throw new Error(`Expected ${partSize} rows in expansion part ${part}, got ${partRows.length}`);
}
const items = json(partRows);
const expectedLoaded = part * partSize;

process.stdout.write(`-- GENERATED by artifacts/api-server/scripts/render-usda-expanded-catalog-seed.ts; DO NOT EDIT.
-- Source: USDA FoodData Central SR Legacy, release 2018-04; part ${part} of 2.
begin;

with seed as (
  select * from jsonb_to_recordset($seed_items$${items}$seed_items$::jsonb) as x(
    kind text, name text, brand text, serving_label text, serving_grams numeric,
    calories numeric, protein numeric, carbs numeric, fat numeric, measures jsonb,
    source text, source_id text, barcode text, quality_status text, provenance jsonb
  )
)
insert into public.food_catalog_items (
  kind, name, brand, serving_label, serving_grams, calories, protein, carbs, fat,
  measures, source, source_id, barcode, quality_status, provenance
)
select kind, name, brand, serving_label, serving_grams, calories, protein, carbs, fat,
  measures, source, source_id, barcode, quality_status, provenance from seed
on conflict (source, source_id) do update set
  kind = excluded.kind, name = excluded.name, brand = excluded.brand,
  serving_label = excluded.serving_label, serving_grams = excluded.serving_grams,
  calories = excluded.calories, protein = excluded.protein, carbs = excluded.carbs,
  fat = excluded.fat, measures = excluded.measures, quality_status = excluded.quality_status,
  provenance = excluded.provenance, updated_at = now();

do $seed_assertions$
begin
  if (select count(*) from public.food_catalog_items
      where source = 'usda_fdc'
        and provenance->>'release' = '2018-04'
        and provenance->>'coachVerdict' = 'unknown'
        and provenance ? 'sourceDescription') < ${expectedLoaded} then
    raise exception 'USDA catalog expansion did not load ${expectedLoaded} rows through part ${part}';
  end if;
end $seed_assertions$;
commit;
`);