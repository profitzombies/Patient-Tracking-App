/**
 * Renders the committed, idempotent Supabase migration from shared reviewed
 * seed data. Run from api-server:
 *   pnpm exec tsx scripts/render-usda-catalog-seed.ts > ../../supabase/migrations/20260925100000_seed_usda_catalog.sql
 *
 * The verifier compares the committed migration to this output, preventing
 * hand edits and ensuring the database cannot silently drift from the catalog.
 */
import {
  USDA_CATALOG_ALIAS_SEED_ROWS,
  USDA_CATALOG_APPROVAL_SEED_ROWS,
  USDA_CATALOG_SEED_ROWS,
} from '../src/catalog/usda-seed';

function json(value: unknown): string {
  // Dollar quoting preserves every official punctuation/quote verbatim.
  const serialized = JSON.stringify(value);
  if (serialized.includes('$seed_')) throw new Error('Seed data conflicts with SQL dollar-quote tag');
  return serialized;
}

const items = json(USDA_CATALOG_SEED_ROWS);
const aliases = json(USDA_CATALOG_ALIAS_SEED_ROWS);
const links = json(USDA_CATALOG_APPROVAL_SEED_ROWS);

process.stdout.write(`-- GENERATED by artifacts/api-server/scripts/render-usda-catalog-seed.ts; DO NOT EDIT.
-- Source digest/count assertions live in verify-usda-essentials.ts.
begin;

with seed as (
  select * from jsonb_to_recordset($seed_items$${items}$seed_items$::jsonb) as x(
    kind text, name text, brand text, serving_label text, serving_grams numeric,
    calories numeric, protein numeric, carbs numeric, fat numeric, measures jsonb,
    source text, source_id text, barcode text, quality_status text, provenance jsonb
  )
)
insert into public.food_catalog_items (
  kind, name, brand, serving_label, serving_grams, calories, protein, carbs, fat,
  measures, source, source_id, barcode, quality_status, provenance
)
select kind, name, brand, serving_label, serving_grams, calories, protein, carbs, fat,
  measures, source, source_id, barcode, quality_status, provenance from seed
on conflict (source, source_id) do update set
  kind = excluded.kind, name = excluded.name, brand = excluded.brand,
  serving_label = excluded.serving_label, serving_grams = excluded.serving_grams,
  calories = excluded.calories, protein = excluded.protein, carbs = excluded.carbs,
  fat = excluded.fat, measures = excluded.measures, quality_status = excluded.quality_status,
  provenance = excluded.provenance, updated_at = now();

with seed as (
  select * from jsonb_to_recordset($seed_aliases$${aliases}$seed_aliases$::jsonb)
    as x(source_id text, alias text, legacy_id text)
)
insert into public.food_catalog_aliases (catalog_id, alias, legacy_id)
select item.id, seed.alias, seed.legacy_id
from seed join public.food_catalog_items item
  on item.source = 'usda_fdc' and item.source_id = seed.source_id
on conflict (catalog_id, alias) do update set legacy_id = excluded.legacy_id;

with seed as (
  select * from jsonb_to_recordset($seed_links$${links}$seed_links$::jsonb)
    as x(source_id text, approved_food_id text, official_name text,
         official_portion text, phase_guidance text, constraints jsonb)
)
insert into public.food_catalog_approved_links (
  catalog_id, approved_food_id, official_name, official_portion, phase_guidance,
  constraints, reviewed_at
)
select item.id, seed.approved_food_id, seed.official_name, seed.official_portion,
  seed.phase_guidance, seed.constraints, '2026-09-25T00:00:00.000Z'::timestamptz
from seed join public.food_catalog_items item
  on item.source = 'usda_fdc' and item.source_id = seed.source_id
on conflict (catalog_id, approved_food_id) do update set
  official_name = excluded.official_name, official_portion = excluded.official_portion,
  phase_guidance = excluded.phase_guidance, constraints = excluded.constraints,
  reviewed_at = excluded.reviewed_at;

do $seed_assertions$
begin
  if (select count(*) from public.food_catalog_items
      where source = 'usda_fdc' and provenance->>'release' = '2018-04') < ${USDA_CATALOG_SEED_ROWS.length} then
    raise exception 'USDA catalog seed did not load all ${USDA_CATALOG_SEED_ROWS.length} rows';
  end if;
  if (select count(*) from public.food_catalog_approved_links
      where reviewed_at = '2026-09-25T00:00:00.000Z'::timestamptz) < ${USDA_CATALOG_APPROVAL_SEED_ROWS.length} then
    raise exception 'USDA catalog seed did not load all ${USDA_CATALOG_APPROVAL_SEED_ROWS.length} approved links';
  end if;
end $seed_assertions$;
commit;
`);