#!/usr/bin/env node
/**
 * Emits src/generated.ts from documents/*.md + documents/version.json so the
 * API, the operations site, and the mobile app (Metro cannot import .md)
 * all ship the exact same text under one version.
 *
 *   node scripts/build-documents.mjs          # rewrite src/generated.ts
 *   node scripts/build-documents.mjs --check  # exit 1 when it is stale
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const documentsDir = join(root, "documents");
const target = join(root, "src", "generated.ts");

const DOCUMENTS = [
  { slug: "privacy", file: "privacy-policy.md", title: "Privacy Policy" },
  { slug: "terms", file: "terms-of-use.md", title: "Terms of Use" },
  { slug: "health-data", file: "health-data-notice.md", title: "Health data notice" },
];

const ISO_DAY = /^\d{4}-\d{2}-\d{2}$/;
const meta = JSON.parse(readFileSync(join(documentsDir, "version.json"), "utf8"));
for (const key of ["version", "effectiveDate"]) {
  if (typeof meta[key] !== "string" || !ISO_DAY.test(meta[key])) {
    throw new Error(`version.json: "${key}" must be an ISO day (YYYY-MM-DD)`);
  }
}
if (meta.status !== "draft" && meta.status !== "final") {
  throw new Error('version.json: "status" must be "draft" or "final"');
}

const documents = DOCUMENTS.map((entry) => {
  const markdown = readFileSync(join(documentsDir, entry.file), "utf8").replace(/\r\n/g, "\n").trim();
  if (!markdown.startsWith(`# ${entry.title}`)) {
    throw new Error(`${entry.file} must start with "# ${entry.title}"`);
  }
  return { ...entry, markdown };
});

const lines = [
  "// GENERATED by scripts/build-documents.mjs from documents/*.md — do not edit.",
  "// Edit the markdown + version.json, then run `pnpm --filter @workspace/legal-documents run build:documents`.",
  "",
  `export const LEGAL_DOCUMENTS_VERSION = ${JSON.stringify(meta.version)};`,
  `export const LEGAL_DOCUMENTS_EFFECTIVE_DATE = ${JSON.stringify(meta.effectiveDate)};`,
  `export const LEGAL_DOCUMENTS_STATUS = ${JSON.stringify(meta.status)} as "draft" | "final";`,
  "",
  "export const GENERATED_DOCUMENTS = [",
  ...documents.map(
    (document) =>
      `  { slug: ${JSON.stringify(document.slug)}, title: ${JSON.stringify(document.title)}, markdown: ${JSON.stringify(document.markdown)} },`,
  ),
  "] as const;",
  "",
];
const next = lines.join("\n");

if (process.argv.includes("--check")) {
  let current = "";
  try {
    current = readFileSync(target, "utf8");
  } catch {
    // Missing file is stale.
  }
  if (current !== next) {
    console.error("lib/legal-documents/src/generated.ts is stale; run build:documents");
    process.exit(1);
  }
  console.log("legal documents: generated.ts matches documents/");
} else {
  writeFileSync(target, next);
  console.log(`legal documents: wrote ${target} (version ${meta.version}, ${meta.status})`);
}
