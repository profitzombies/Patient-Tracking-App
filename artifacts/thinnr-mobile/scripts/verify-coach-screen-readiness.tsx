import React, { act } from "react";
import { create, type ReactTestRenderer } from "react-test-renderer";
import assert from "node:assert/strict";
import CoachChatScreen from "../app/coach-chat";
import { state } from "./coach-readiness-stubs/screen-context";
import { setChatAccountParams } from "./chat-account-stubs/expo-router";

(globalThis as Record<string, unknown>).IS_REACT_ACT_ENVIRONMENT = true;
let tree: ReactTestRenderer;
const nodes = (id: string) => tree.root.findAll(n => n.props.testID === id);
const props = (id: string) => nodes(id)[0]?.props;
const render = async () => { await act(async () => tree.update(<CoachChatScreen />)); };

async function main() {
  setChatAccountParams({ messageId: "not-yet-loaded" });
  await act(async () => { tree = create(<CoachChatScreen />); });
  assert.ok(nodes("coach-back").length && nodes("coach-history").length, "safe header is usable while transcript held");
  assert.ok(nodes("coach-transcript-loading").length, "unknown transcript has matched bubbles");
  assert.equal(props("coach-transcript-loading")["aria-busy"], true);
  assert.equal(props("coach-input").editable, false);
  assert.equal(props("coach-send").disabled, true);
  assert.equal(props("coach-photo").disabled, true);
  assert.equal(nodes("coach-starter-0").length, 0);
  assert.equal(nodes("coach-source-unavailable").length, 0, "source not missing until hydration settles");
  state.isConversationLoading = false;
  state.conversationError = "Could not load this conversation. Check your connection and retry.";
  await render();
  assert.equal(nodes("coach-transcript-loading").length, 0, "error is not indefinite loading");
  assert.ok(nodes("coach-conversation-retry").length);
  assert.equal(props("coach-input").editable, false, "failed unknown destination cannot send");
  await act(async () => { props("coach-conversation-retry").onPress(); });
  assert.equal(state.refreshCalls.at(-1), true, "Retry bypasses freshness");
  state.hasConversationLoaded = true;
  state.conversationError = null;
  state.messages = [{ id: "not-yet-loaded", role: "user", status: "done", text: "My saved message" }];
  await render();
  await act(async () => { props("coach-input").onChangeText("Unsent draft"); });
  state.isConversationRefreshing = true;
  await render();
  assert.equal(props("coach-input").value, "Unsent draft", "refresh preserves unsent composer");
  assert.ok(JSON.stringify(tree.toJSON()).includes("My saved message"));
  assert.equal(nodes("coach-transcript-loading").length, 0, "cached background refresh never replaces content");
  assert.ok(nodes("coach-refresh-status").length);
  state.isStreaming = true;
  await render();
  assert.ok(nodes("coach-stop").length, "Stop remains available during an active stream");
  state.isStreaming = false;
  state.isConversationRefreshing = false;
  state.hasOlderMessages = true;
  state.isLoadingOlder = true;
  await render();
  assert.ok(nodes("coach-older-loading").length);
  assert.ok(JSON.stringify(tree.toJSON()).includes("My saved message"), "older loading retains transcript");
  state.conversationScopeKey = "account:epoch-1:thread-b";
  state.messages = [];
  state.isLoadingOlder = false;
  state.isConversationLoading = true;
  state.hasConversationLoaded = false;
  await render();
  assert.equal(props("coach-input").value, "", "new destination clears old draft");
  assert.equal(props("coach-photo").disabled, true);
  await act(async () => { props("coach-send").onPress(); });
  assert.equal(state.sendCalls.length, 0);
  await act(async () => tree.unmount());
  console.log("✓ coach screen readiness: held shell, error/retry, cached draft, Stop, paging and selection guards");
}
void main().catch(error => { console.error(error); process.exitCode = 1; });